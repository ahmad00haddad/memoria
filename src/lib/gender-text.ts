function compile(dict: Record<string, string>) {
  // الأطول أولاً حتى لا تبتلع كلمة قصيرة جزءاً من عبارة أطول
  const keys = Object.keys(dict).sort((a, b) => b.length - a.length).map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  // حرف عطف ملتصق اختياري (وأكملي، فراسليها) يبقى كما هو
  return new RegExp(`(?<![${AR}])(و|ف)?(${keys.join("|")})(?![${AR}])`, "g");
}
const swap = (dict: Record<string, string>) => (_m: string, pre: string | undefined, w: string) => (pre ?? "") + (dict[w] ?? w);
const SECOND_RE = compile(SECOND);
const THIRD_RE = compile(THIRD);
// كِ المشكولة = مخاطَبة مؤنّثة (حسابكِ، عليكِ، لكِ)
const KASRA_K = /كِ/g;
// تِ المشكولة في آخر الفعل الماضي (وافقتِ، ألغيتِها) — تبقى ها/ه بعدها
const KASRA_T = new RegExp(`تِ(?=ه|ها|[^${AR}]|$)`, "g");

/** مخاطبة المصوّر (المذكّر) بدل المصوّرة. */
export function secondToMale(text: string): string {
  if (!text) return text;
  return text
    .replace(SECOND_RE, swap(SECOND))
    .replace(/أنتِ/g, "أنت")
    .replace(KASRA_K, "ك")
    .replace(KASRA_T, "ت");
}

/** الحديث عن المصوّر (المذكّر) بدل المصوّرة، في نص موجّه للعروس. */
export function thirdToMale(text: string): string {
  if (!text) return text;
  return text.replace(THIRD_RE, swap(THIRD));
}

/** نفس الفكرة للنص الإنجليزي (she/her → he/his/him). */
export function thirdToMaleEn(text: string): string {
  if (!text) return text;
  return text
    .replace(/\b(send|ask|message|tell|contact|pay|give|show|let|remind|call|text|thank|asks|lets|gives) her\b/gi, "$1 him")
    .replace(/\bshe['’]ll\b/g, "he’ll").replace(/\bShe\b/g, "He").replace(/\bshe\b/g, "he")
    .replace(/\bherself\b/g, "himself").replace(/\bhers\b/g, "his").replace(/\bHer\b/g, "His").replace(/\bher\b/g, "his");
}

